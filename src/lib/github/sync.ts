import { createHash } from "node:crypto";
import { createAdminClient } from "@/lib/supabase/admin";
import {
  createGithubRepository,
  ensureRepositoryInstallationAccess,
  getValidGithubConnection,
  pushRepositorySnapshot,
  readRepositorySnapshot,
  repositoryNameFromProject,
} from "@/lib/github/client";
import type { SourceFile } from "@/lib/sandbox/build";

const SOURCE_FILE_PATTERN = /\.(?:ts|tsx|js|jsx|mjs|cjs|css|scss|sass|less|html|json|md|sql|toml|ya?ml|graphql|gql|svg)$/i;
const SOURCE_BASENAMES = new Set([".gitignore", ".npmignore", "Dockerfile"]);

export async function syncProjectToGithub(projectId: string, userId: string) {
  const admin = createAdminClient();
  const { data: project, error: projectError } = await admin
    .from("projects")
    .select("id,owner_id,name,description,current_version_id,github_repo_id,github_repo_full_name,github_default_branch")
    .eq("id", projectId)
    .single();
  if (projectError || !project || project.owner_id !== userId) throw new Error("Project not found or access denied");
  if (!project.current_version_id) throw new Error("Generate an application version before connecting GitHub");

  await admin.from("projects").update({ github_sync_status: "syncing", github_sync_error: null }).eq("id", projectId);

  try {
    const { connection, accessToken } = await getValidGithubConnection(userId);
    if (!connection.installation_id) throw new Error("Install the LYMTLESS GitHub App on your personal GitHub account before syncing a repository");

    let repoId = project.github_repo_id as number | null;
    let fullName = project.github_repo_full_name as string | null;
    let branch = (project.github_default_branch as string | null) || "main";

    if (!repoId || !fullName) {
      const repo = await createGithubRepository(
        accessToken,
        repositoryNameFromProject(project.name, project.id),
        project.description || `Generated by LYMTLESS AI BUILDER — ${project.name}`,
      );
      await ensureRepositoryInstallationAccess(accessToken, connection.installation_id, repo.id);
      repoId = repo.id;
      fullName = repo.full_name;
      branch = repo.default_branch || "main";
      await admin.from("projects").update({
        github_repo_id: repoId,
        github_repo_full_name: fullName,
        github_default_branch: branch,
        github_sync_status: "connected",
      }).eq("id", projectId);
    }

    const { data: files, error: fileError } = await admin
      .from("generated_files")
      .select("path,content,content_hash")
      .eq("version_id", project.current_version_id)
      .order("path", { ascending: true });
    if (fileError || !files?.length) throw new Error(fileError?.message || "Current generated version has no source files");

    const { data: version } = await admin
      .from("versions")
      .select("version_number")
      .eq("id", project.current_version_id)
      .single();

    const commitSha = await pushRepositorySnapshot({
      token: accessToken,
      fullName,
      branch,
      files: files as SourceFile[],
      message: `[LYMTLESS] Sync version ${version?.version_number ?? "current"}`,
    });

    const { error: projectUpdateError } = await admin.from("projects").update({
      github_last_synced_sha: commitSha,
      github_sync_status: "synced",
      github_sync_error: null,
    }).eq("id", projectId);
    if (projectUpdateError) throw new Error(projectUpdateError.message);
    await admin.from("versions").update({ git_commit_sha: commitSha }).eq("id", project.current_version_id);

    return { repoId, fullName, branch, commitSha };
  } catch (error) {
    const message = error instanceof Error ? error.message : "GitHub sync failed";
    await admin.from("projects").update({ github_sync_status: "failed", github_sync_error: message.slice(0, 5000) }).eq("id", projectId);
    throw error;
  }
}

export async function importGithubCommit(options: {
  projectId: string;
  userId: string;
  repoFullName: string;
  commitSha: string;
}) {
  const admin = createAdminClient();
  const { accessToken } = await getValidGithubConnection(options.userId);
  const snapshot = await readRepositorySnapshot({
    token: accessToken,
    fullName: options.repoFullName,
    commitSha: options.commitSha,
  });
  const files = snapshot.filter((file) => isAllowedImportedSource(file.path));
  if (!files.some((file) => file.path === "package.json")) {
    throw new Error("GitHub import was rejected because package.json was not present in the allowed source snapshot");
  }

  const payload = files.map((file) => ({
    path: file.path,
    content: file.content,
    content_hash: createHash("sha256").update(file.content, "utf8").digest("hex"),
  }));

  const { data, error } = await admin.rpc("commit_github_import", {
    p_project_id: options.projectId,
    p_user_id: options.userId,
    p_commit_sha: options.commitSha,
    p_summary: `Imported GitHub commit ${options.commitSha.slice(0, 12)}`,
    p_files: payload,
  });
  if (error) throw new Error(`Could not import GitHub commit: ${error.message}`);
  const row = Array.isArray(data) ? data[0] : data;
  return { versionId: row?.id as string | undefined, versionNumber: row?.version_number as number | undefined, files: files.length };
}

function isAllowedImportedSource(path: string) {
  const basename = path.split("/").at(-1) || "";
  return SOURCE_BASENAMES.has(basename) || SOURCE_FILE_PATTERN.test(path);
}
